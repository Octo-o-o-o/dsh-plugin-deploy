const NPM_PACKAGES = ['@deepseek-ai/dsh', '@deepseek-ai/dsh-tools', '@deepseek-ai/dsh-agent',
  '@deepseek-ai/dsh-client-ui-renderer', '@deepseek-ai/dsh-client-store',
  '@deepseek-ai/dsh-client-ui-slots', '@deepseek-ai/dsh-client-ui-primitives',
  '@deepseek-ai/dsh-client-ui-attachment', '@deepseek-ai/cordis']
async function fetchNpm() {
  const rows = []
  for (const name of NPM_PACKAGES) {
    try {
      const r = await fetch(`https://registry.npmjs.org/${encodeURIComponent(name).replace('%40', '@')}`, { headers: { accept: 'application/vnd.npm.install-v1+json' }, signal: AbortSignal.timeout(15_000) })
      if (!r.ok) { rows.push({ name, latest: `(HTTP ${r.status})`, next: '', modified: '' }); continue }
      const j = await r.json()
      rows.push({ name, latest: j['dist-tags']?.latest ?? '', next: j['dist-tags']?.next ?? '', modified: (j.modified ?? '').slice(0, 10) })
    } catch (e) { rows.push({ name, latest: `(error: ${e.message})`, next: '', modified: '' }) }
  }
  return rows
}

