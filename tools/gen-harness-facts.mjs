// ---------- git helpers（全部只读） ----------
function git(...a) {
  return execFileSync('git', ['-C', opt.repo, ...a], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'pipe'] })
}
function tryGit(...a) { try { return git(...a) } catch { return null } }
const COMMIT = tryGit('rev-parse', `${opt.ref}^{commit}`)?.trim()
if (!COMMIT) { console.error(`gen-facts: cannot resolve ref ${opt.ref} in ${opt.repo}`); process.exit(64) }
const COMMIT_DATE = git('show', '-s', '--format=%cI', COMMIT).trim()
const COMMIT_SUBJECT = git('show', '-s', '--format=%s', COMMIT).trim()
function show(path) { return tryGit('show', `${COMMIT}:${path}`) }
function exists(path) { return tryGit('cat-file', '-e', `${COMMIT}:${path}`) !== null }
function grepFiles(needle, pathspecs) {
  const out = tryGit('grep', '-l', '-F', '-e', needle, COMMIT, '--', ...pathspecs) ?? ''
  return out.split('\n').filter(Boolean).map(l => l.replace(`${COMMIT}:`, ''))
}
function grepLines(needle, path, fixed = true) {
  const out = tryGit('grep', '-n', ...(fixed ? ['-F'] : ['-E']), '-e', needle, COMMIT, '--', path) ?? ''
  return out.split('\n').filter(Boolean).map(l => {
    const rest = l.slice(l.indexOf(':') + 1) // strip "<commit>:"
    const m = rest.match(/^([^:]+):(\d+):(.*)$/)
    return m ? { file: m[1], line: Number(m[2]), text: m[3] } : null
  }).filter(Boolean)
}
function nearestPackageName(file) {
  let dir = dirname(file)
  while (dir && dir !== '.' && dir !== '/') {
    const pj = show(`${dir}/package.json`)
    if (pj) { try { return JSON.parse(pj).name ?? dir } catch { return dir } }
    dir = dirname(dir)
  }
  return '(root)'
}
function lastCommitTouching(needle, pathspec) {
  return tryGit('log', '-S', needle, '--format=%h %ad %s', '--date=short', '-1', COMMIT, '--', pathspec)?.trim() || ''
}

