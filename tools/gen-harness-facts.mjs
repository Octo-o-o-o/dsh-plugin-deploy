// ---------- 1. slots ----------
function extractSlots() {
  const files = grepFiles('interface SlotMap', ['packages', 'apps'])
    .filter(f => !/\/tests?\/|\.spec\.|\.test\.|api-catalog/.test(f))
  const slots = []
  for (const file of files) {
    const src = show(file)
    if (!src) continue
    const blanked = blankComments(src)
    let searchFrom = 0
    while (true) {
      const at = blanked.indexOf('interface SlotMap', searchFrom)
      if (at === -1) break
      const open = blanked.indexOf('{', at)
      const close = open === -1 ? -1 : matchBrace(blanked, open)
      if (open === -1 || close === -1) break
      const block = blanked.slice(open + 1, close)
      const blockOffset = open + 1
      const entryRe = /'([A-Za-z0-9_.\-]+)'\s*:\s*\{/g
      let m
      while ((m = entryRe.exec(block)) !== null) {
        const bodyOpen = blockOffset + m.index + m[0].length - 1
        const bodyClose = matchBrace(blanked, bodyOpen)
        if (bodyClose === -1) continue
        const body = blanked.slice(bodyOpen + 1, bodyClose)
        // 只取顶层键（花括号深度 0）
        const keys = []
        let depth = 0
        for (let i = 0; i < body.length; i++) {
          const ch = body[i]
          if (ch === '{') depth++
          else if (ch === '}') depth--
          else if (depth === 0) {
            const km = /^([A-Za-z_][A-Za-z0-9_]*)\s*:/.exec(body.slice(i))
            if (km && (i === 0 || /[\s;,{]/.test(body[i - 1]))) { keys.push(km[1]); i += km[0].length - 1 }
          }
        }
        const kind = /\bkind\s*:\s*'([^']+)'/.exec(body)?.[1] ?? '?'
        const scope = /\bscope\s*:\s*'([^']+)'/.exec(body)?.[1] ?? '?'
        const owner = /\bowner\s*:\s*([^\n;]+)/.exec(body)?.[1]?.trim() ?? ''
        slots.push({
          name: m[1], kind, scope, owner,
          extra: keys.filter(k => !['kind', 'scope', 'owner'].includes(k)),
          file, line: lineOf(src, blockOffset + m.index), pkg: nearestPackageName(file),
        })
        entryRe.lastIndex = bodyClose - blockOffset
      }
      searchFrom = close
    }
  }
  slots.sort((a, b) => a.name.localeCompare(b.name))
  const dupes = slots.map(s => s.name).filter((n, i, arr) => arr.indexOf(n) !== i)
  if (dupes.length) status.notes.push(`slot 重复声明: ${[...new Set(dupes)].join(', ')}`)
  return slots
}

// ---------- 2. externals ----------
function extractExternals() {
  const platform = show('packages/client/web/src/platform.ts')
  const tsdown = show('packages/client/tsdown.client.ts')
  const res = { platformModules: [], preloadedExternals: [], banner: null, intro: null, footer: null, purity: null, files: [] }
  if (platform) {
    res.files.push('packages/client/web/src/platform.ts')
    const arr = /PLATFORM_MODULES\s*=\s*\[([\s\S]*?)\]/.exec(platform)?.[1] ?? ''
    res.platformModules = [...arr.matchAll(/'([^']+)'/g)].map(x => x[1])
    const preloaded = /PRELOADED_CLIENT_EXTERNALS\s*=\s*\[([\s\S]*?)\]/.exec(platform)?.[1] ?? ''
    res.preloadedExternals = [...preloaded.matchAll(/'([^']+)'/g)].map(x => x[1])
    if (!/\bPRELOADED_CLIENT_EXTERNALS\b/.test(platform)) {
      status.anchorsMissing.push('platform.ts PRELOADED_CLIENT_EXTERNALS')
    }
  } else status.anchorsMissing.push('packages/client/web/src/platform.ts (PLATFORM_MODULES)')
  if (tsdown) {
    res.files.push('packages/client/tsdown.client.ts')
    res.banner = tsdown.split('\n').find(l => l.includes('banner:'))?.trim() ?? null
    res.intro = tsdown.split('\n').find(l => l.includes('intro:'))?.trim() ?? null
    res.footer = tsdown.split('\n').find(l => l.includes('footer:'))?.trim() ?? null
    res.purity = tsdown.split('\n').find(l => l.includes('client bundle purity'))?.trim() ?? null
    if (!/\bPRELOADED_CLIENT_EXTERNALS\b/.test(tsdown)) status.anchorsMissing.push('tsdown.client.ts PRELOADED_CLIENT_EXTERNALS')
    if (!res.banner) status.anchorsMissing.push('tsdown.client.ts banner')
    if (!res.intro) status.anchorsMissing.push('tsdown.client.ts intro (module/exports 声明)')
  } else status.anchorsMissing.push('packages/client/tsdown.client.ts')
  return res
}

// ---------- 3. dsh.client manifest ----------
function extractClientManifest() {
  const file = 'packages/util/package-manifest/src/types.ts'
  const parser = 'packages/client/modules/src/client/manifest.ts'
  const routeFile = 'packages/client/modules/src/index.ts'
  const src = show(file)
  const res = { file, parser, routeFile, declInterface: null, errors: [], route: null }
  if (!src) { status.anchorsMissing.push(file); return res }
  res.declInterface = /export interface DshClientManifest \{[\s\S]*?\n\}/.exec(src)?.[0] ?? null
  if (!res.declInterface) status.anchorsMissing.push(`${file} DshClientManifest`)
  res.errors = (show(parser) ?? '').split('\n').map((l, i) => ({ line: i + 1, text: l.trim() }))
    .filter(x => x.text.includes('client-modules:') && x.text.includes('Error('))
  res.route = (show(routeFile) ?? '').split('\n').map((l, i) => ({ line: i + 1, text: l.trim() }))
    .find(x => x.text.includes('const prefix = `/plugins/${record.entry.id}/`')) ?? null
  if (!res.route) status.anchorsMissing.push(`${routeFile} /plugins/<id>/ resource route`)
  return res
}

// ---------- 4. settings namespaces ----------
function extractSettingsNamespaces() {
  const hits = grepFiles('WEB_SETTINGS_NAMESPACES', ['packages'])
  const res = { present: hits.length > 0, files: hits, values: [], lastTouch: '' }
  if (res.present) {
    for (const f of hits) {
      const src = show(f) ?? ''
      const arr = /WEB_SETTINGS_NAMESPACES\s*=\s*\[([\s\S]*?)\]/.exec(src)?.[1]
      if (arr) res.values = [...arr.matchAll(/'([^']+)'/g)].map(x => x[1])
    }
  } else {
    res.lastTouch = lastCommitTouching('WEB_SETTINGS_NAMESPACES', 'packages')
  }
  return res
}

// ---------- 5. CLI ----------
function extractCli() {
  const argsSrc = show('apps/cli/src/args.ts')
  const pluginSrc = show('apps/cli/src/plugin.ts')
  const res = { usage: [], options: [], pluginHeader: [], required: [] }
  if (!argsSrc) status.anchorsMissing.push('apps/cli/src/args.ts')
  else {
    res.usage = argsSrc.split('\n').filter(l => /^\s{2,}dsh /.test(l)).map(l => l.trim())
    const seen = new Set()
    res.options = [...argsSrc.matchAll(/\.option\('([^']+)',\s*'((?:[^'\\]|\\.)*)'/g)]
      .map(x => ({ flag: x[1], help: x[2].replace(/\\'/g, "'") }))
      .filter(o => { const k = o.flag + '|' + o.help; if (seen.has(k)) return false; seen.add(k); return true })
    res.required = [...argsSrc.matchAll(/error:\s*([^'"`]*is required[^'"`]*)/g)].map(x => x[1].trim())
  }
  if (!pluginSrc) status.anchorsMissing.push('apps/cli/src/plugin.ts')
  else {
    const header = pluginSrc.match(/\/\*\* Run package management for a profile\.[\s\S]*?\*\//)?.[0] ?? ''
    res.pluginHeader = header.split('\n').map(l => l.replace(/^\s*(?:\/\*\*|\*\/?)[ ]?/, '').trim()).filter(Boolean)
    if (!header) status.anchorsMissing.push('apps/cli/src/plugin.ts runPlugin documentation')
  }
  return res
}

// ---------- 6. events ----------
function extractEvents() {
  const file = 'docs/event-producer-consumer.md'
  const src = show(file)
  const res = { file, events: [] }
  if (!src) { status.anchorsMissing.push(file); return res }
  for (const line of src.split('\n')) {
    const m = /^\|\s*`([^`]+)`\s*\|\s*`([^`]+)`\s*\|\s*\[`([^`]+)`\]/.exec(line)
    if (m) res.events.push({ name: m[1], mode: m[2], declaredIn: m[3] })
  }
  if (res.events.length === 0) status.anchorsMissing.push(`${file} table rows`)
  return res
}

